"use strict";
const assert = require("node:assert/strict");
const spec = require("../src/data/master-frame-spec.js");
const result = spec.validate();
assert.equal(result.ok, true, result.errors.join(", "));
assert.deepEqual(spec.ASPECT_RATIO, [16, 9]);
